const dictionaries: Record<Locale, Dict> = { no, en }

export function translate(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  const raw = dictionaries[locale][key] ?? dictionaries.no[key] ?? key
  if (!vars) return raw
  return Object.entries(vars).reduce(
    (s, [k, v]) => s.replace(`{${k}}`, String(v)),
    raw,
  )
}

export function formatLabel(locale: Locale, format: TournamentFormat): string {
  return translate(locale, `format_${format}`)
}

export function formatDescription(locale: Locale, format: TournamentFormat): string {
  return translate(locale, `formatDesc_${format}`)
}

export function localizedRoundLabel(
  locale: Locale,
  format: TournamentFormat,
  round: number,
  totalRounds: number,
): string {
  if (format === 'round_robin') return translate(locale, 'roundMatches')
  if (format === 'league' || format === 'swiss') return translate(locale, 'roundN', { n: round })
  if (round === totalRounds) return translate(locale, 'final')
  if (round === totalRounds - 1) return translate(locale, 'semifinal')
  if (round === totalRounds - 2) return translate(locale, 'quarterfinal')
  return translate(locale, 'roundN', { n: round })
}
